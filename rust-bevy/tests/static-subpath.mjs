import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const base = 'http://127.0.0.1:5184/eval-gpu/rust-bevy/';
const server = spawn(process.execPath, ['scripts/pages-preview.mjs'], { stdio: ['ignore', 'pipe', 'pipe'] });
let browser;
const results = { base, nodeVersion: process.version, cssViewport: [1440, 960], deviceScaleFactor: 2 }, errors = [], requests = [], failures = [], messages = [];
try {
  await new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(Error('Static preview did not start')), 15000);
    server.stdout.on('data', data => { if (data.toString().includes('STATIC_READY')) { clearTimeout(timer); resolve(); } });
    server.stderr.on('data', data => { clearTimeout(timer); reject(Error(data.toString())); });
    server.on('exit', code => { clearTimeout(timer); reject(Error(`Preview exited: ${code}`)); });
  });
  // Origin-root paths intentionally fail, making accidental absolute imports observable.
  assert.equal((await fetch('http://127.0.0.1:5184/pkg/lattice.js')).status, 404);
  browser = await chromium.launch({ headless: false, executablePath: process.env.CHROME_EXECUTABLE || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', args: ['--enable-unsafe-webgpu', '--no-first-run'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, deviceScaleFactor: 2 });
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { messages.push(m.text()); if (m.type() === 'error' || /\bERROR\b/.test(m.text())) errors.push(m.text()); });
  page.on('response', r => { requests.push({ url: r.url(), status: r.status() }); if (r.status() >= 400) failures.push({ url: r.url(), status: r.status() }); });
  page.on('requestfailed', r => failures.push({ url: r.url(), failure: r.failure() }));
  const snapshot = () => page.evaluate(() => ({ url: location.href, stats: rustStats, frame: frameStats, dpr: devicePixelRatio, quality: document.querySelector('#quality').value, backing: [document.querySelector('#scene').width, document.querySelector('#scene').height] }));
  const native = s => { assert.deepEqual(s.backing, [2880, 1920]); assert.equal(s.dpr, 2); assert.equal(s.quality, '1'); assert.equal(s.frame.adaptive, false); };
  const wait = ms => page.waitForTimeout(ms);
  await page.goto(base);
  await page.waitForFunction(() => window.rustStats?.crystals === 784, null, { timeout: 120000 });
  await wait(2500);
  results.original = await snapshot(); native(results.original);
  await page.screenshot({ path: 'tests/static-original.png' });
  assert.ok(requests.some(r => r.url === base + 'assets/shaders/interference.wgsl' && r.status === 200), 'Bevy must fetch the real custom WGSL under the nested path');
  const core = await page.evaluate(() => ({ x: rustStats.coreX, y: rustStats.coreY }));
  await page.mouse.click(1020, 110); await wait(350);
  assert.equal((await snapshot()).stats.selected, -1);
  await page.mouse.click(core.x, core.y); await wait(350);
  assert.equal((await snapshot()).stats.selected, 0); results.originalPicking = true;
  await page.locator('[data-level="100"]').click();
  await page.waitForFunction(() => rustStats.crystals === 6049, null, { timeout: 45000 });
  await wait(700); results.originalMaximum = await snapshot(); native(results.originalMaximum);
  await page.locator('.scene-switch a[href="./?scene=exhibition"]').click();
  assert.equal(new URL(page.url()).pathname, '/eval-gpu/rust-bevy/');
  await page.waitForFunction(() => window.rustStats?.people === 120, null, { timeout: 120000 });
  await wait(2000); results.exhibition = await snapshot(); native(results.exhibition);
  assert.equal(results.exhibition.stats.night, false);
  await page.screenshot({ path: 'tests/static-exhibition-day.png' });
  await page.locator('#destination').selectOption('24');
  await page.waitForFunction(() => rustStats.selected === 24);
  results.route = (await snapshot()).stats.route;
  assert.ok(results.route.some(p => p[1] === 31), 'Cafe route uses its obstacle detour');
  assert.ok((await snapshot()).stats.routeDistance > 0);
  await page.locator('#overhead').click(); await wait(500);
  await page.locator('.map-label[data-id="14"]').click();
  await page.waitForFunction(() => rustStats.selected === 14); results.labelPicking = true;
  await page.locator('#orbit-view').click(); await wait(400);
  await page.locator('#night').check();
  await page.waitForFunction(() => rustStats.night === true);
  await wait(600); results.night = await snapshot(); native(results.night);
  await page.screenshot({ path: 'tests/static-exhibition-night.png' });
  await page.locator('[data-level="100"]').click();
  await page.waitForFunction(() => rustStats.people === 1200, null, { timeout: 45000 });
  await wait(700); results.exhibitionMaximum = await snapshot(); native(results.exhibitionMaximum);
  await page.locator('#quality').selectOption('0.5'); await wait(600);
  assert.deepEqual((await snapshot()).backing, [1440, 960]); results.manual50 = true;
  await page.locator('#quality').selectOption('1');
  await page.locator('.scene-switch a[href="./"]').click();
  await page.waitForFunction(() => window.rustStats?.crystals === 784, null, { timeout: 60000 });
  await wait(500); results.returnOriginal = await snapshot(); native(results.returnOriginal);
  assert.ok(requests.some(r => r.url === base + 'pkg/lattice_bg.wasm' && r.status === 200));
  assert.ok(requests.some(r => r.url.includes('/pkg/snippets/') && r.status === 200));
  assert.ok(messages.some(m => m.includes('BrowserWebGpu')));
  assert.equal(errors.length, 0, errors.join('\n')); assert.equal(failures.length, 0, JSON.stringify(failures));
  assert.ok(requests.every(r => r.url.startsWith(base)), 'All runtime network requests stay under the deployment directory');
  results.passed = true;
} catch (e) { results.passed = false; results.failure = e.stack; }
finally {
  if (browser) await browser.close();
  server.kill('SIGTERM');
  fs.writeFileSync('tests/static-subpath-results.json', JSON.stringify({ results, errors, failures, requests, messages }, null, 2));
  console.log(JSON.stringify({ results, errors, failures }, null, 2));
}
if (!results.passed) process.exitCode = 1;
